"""Правила разметки звонков: реальные расшифровки + ловушки, на которых правила уже спотыкались."""
from datetime import date

from calls_tagger.tags import classify, detect_type, find_date, find_players, norm_text

DAY = date(2026, 10, 9)

# Реальные куски расшифровок (09.10.2026), как их отдаёт Whisper.
CORP = ("такому поиграть у вас пиньболг прекрасно какая дата вас интересует 31 октября "
        "сколько вас спанируются участников какого возраста здрослые это такая корпоративная "
        "программа у нас будет где то примерно человек 30")
PLAY_TEN = ("как сказать забронировать на 10 человек площадку площадка город называется "
            "а в среднем сколько идет 2 часа")
ROBOT = ("убедительная просьба является должником по внесению платы как победителя "
         "в электронных процедурах размер задолженности составляет 12 000 рублей")
TOMORROW = ("хочем вот спинбол то играть ох накоммунись на ваша объявленье "
            "ну так я понял завтра на 15 00 да есть время у вас будут классные перчатки защиты")
CORP_ORG = ("меня николай зовут я занимаюсь организацией корпоративных мероприятий и хотел бы "
            "разузнать у нас где то 40 человек")


def test_norm_text_убирает_мусор():
    assert norm_text("Ёлка, 5 человек!") == "елка 5 человек"


def test_корпоратив_с_датой_и_игроками():
    t = classify(CORP, DAY)
    assert t["type"] == "корпоратив"
    assert t["date"]["date"] == "2026-10-31"
    assert t["date"]["kind"] == "explicit"
    assert t["players"]["players"] == 30


def test_в_среднем_не_считается_датой():
    t = classify(PLAY_TEN, DAY)
    assert t["type"] == "просто_игра"
    assert t["date"] is None
    assert t["players"]["players"] == 10


def test_робот_нецелевой():
    t = classify(ROBOT, DAY)
    assert t["type"] == "нецелевой"
    assert t["date"] is None and t["players"] is None


def test_завтра_как_дата_и_классные_перчатки_не_школа():
    t = classify(TOMORROW, DAY)
    assert t["type"] == "просто_игра"
    assert t["date"]["date"] == "2026-10-10"
    assert t["date"]["kind"] == "relative"


def test_организатор_мероприятий_это_корпоратив():
    t = classify(CORP_ORG, DAY)
    assert t["type"] == "корпоратив"
    assert t["players"]["players"] == 40
    assert t["date"] is None  # «зимой» — даты нет, и это честно


def test_слово_будет_не_делает_звонок_детским():
    """«дет» сидит внутри «будет» — раньше это ломало тип."""
    assert detect_type("завтра будет 30 человек, хотим поиграть") == {
        "type": "просто_игра", "why": "поиграт"}


def test_детский_день_рождения():
    t = detect_type("интересует детский день рождения, придёт 10 детей")
    assert t["type"] == "детский"


def test_школьный_класс_отдельный_тип():
    t = detect_type("здравствуйте, мы 8 класс, хотим с классом приехать, учитель с нами")
    assert t["type"] == "школьная_группа"


def test_детский_приоритетнее_корпоратива():
    assert detect_type("корпоратив для сотрудников, но с детьми")["type"] == "детский"


def test_юбилей_взрослых():
    assert detect_type("хотим отпраздновать юбилей, 20 друзей")["type"] == "праздник_взрослые"


def test_пустой_разговор_непонятно():
    assert detect_type("алло да здравствуйте да хорошо")["type"] == "непонятно"


def test_дата_в_прошлом_месяце_переезжает_на_следующий_год():
    d = find_date("приедем 5 января", date(2026, 12, 20))
    assert d["date"] == "2027-01-05"


def test_словом_число_игроков():
    assert find_players("нас будет человек тридцать")["players"] == 30


def test_цена_не_считается_игроками():
    assert find_players("стоимость 3000 рублей с человека") is None


def test_суббота_как_ближайшая_будущая():
    d = find_date("хотим в субботу приехать", DAY)  # 09.10.2026 — пятница
    assert d["date"] == "2026-10-10"


def test_перезвонить_в_понедельник_это_не_дата_игры():
    assert find_date("в понедельник наберу вам, спасибо", DAY) is None


def test_число_словами_перед_единицей():
    assert find_players("придут два человека")["players"] == 2
    assert find_players("нас будет двадцать человек")["players"] == 20


def test_семнадцатого_числа():
    d = find_date("а можно на 17-го числа забронировать", DAY)
    assert d["date"] == "2026-10-17"


def test_непонятный_звонок_без_даты_и_игроков():
    """Про платёж, а не про игру: и тип честный, и ни даты, ни числа не выдумываем."""
    t = classify("я там оплатил, можете глянуть, на понедельник наберу", DAY)
    assert t["type"] == "непонятно"
    assert t["date"] is None and t["players"] is None
