    ("пятьдесят", 50), ("десять", 10), ("девять", 9), ("восемь", 8), ("семь", 7),
    ("шесть", 6), ("пять", 5), ("четыре", 4), ("три", 3), ("два", 2), ("две", 2),
    ("пара", 2),
