# Слова-«звоню вам завтра»: это не дата игры.
CALLBACK = ("наберу", "перезвон", "позвоню", "позвонит", "набрать", "жду звонка", "созвоним")

PEOPLE_UNITS = ("человек", "чел ", "участник", "гост", "детей", "ребят", "персон")
BAD_UNITS = ("рубл", "тысяч", "шарик", "шаров", "шало", "шали", "минут", "час", "секунд",
             "процент", "₽", "штук", "бое")

MONTH_GEN = ("января", "февраля", "марта", "апреля", "мая", "июня", "июля",
             "августа", "сентября", "октября", "ноября", "декабря")


def norm_text(text: str) -> str:
    """Нижний регистр, ё→е, только буквы/цифры/пробелы, одиночные пробелы."""
    s = (text or "").lower().replace("ё", "е")
    s = re.sub(r"[^а-я0-9]+", " ", s)
    return re.sub(r"\s+", " ", s).strip()


def _hit(text: str, stems) -> str | None:
    """Первое совпадение: строка ищется как подстрока, скомпилированный шаблон — как регэксп."""
    for stem in stems:
        if hasattr(stem, "search"):
            m = stem.search(text)
            if m:
                return m.group(0)
        elif stem in text:
            return stem
    return None


def detect_type(text: str) -> dict:
    """Тип запроса + фраза-признак, по которой решили."""
    t = norm_text(text)
    hit = _hit(t, NO_ANSWER)
    if hit:
        return {"type": "недозвон", "why": hit}
    hit = _hit(t, NON_TARGET)
    if hit:
        return {"type": "нецелевой", "why": hit}
    hit = _hit(t, SCHOOL)
    if hit:
        return {"type": "школьная_группа", "why": hit}
    hit = _hit(t, CHILD)
    if hit:
        return {"type": "детский", "why": hit}
    hit = _hit(t, CORPORATE)
    if hit:
        return {"type": "корпоратив", "why": hit}
    hit = _hit(t, ADULT_PARTY)
    if hit:
        return {"type": "праздник_взрослые", "why": hit}
    hit = _hit(t, PLAY)
    if hit:
        return {"type": "просто_игра", "why": hit}
    return {"type": "непонятно", "why": None}


def _word_number(chunk: str) -> int | None:
    """«тридцать первое» → 31, «двадцать» → 20, «восьмое» → 8."""
    tens = units = 0
    for stem, val in TENS:
        if stem in chunk:
            tens = val
            break
    for stem, val in UNITS:
        if stem in chunk:
            units = val
            break
    if tens and units:
        return tens + units
    return tens or units or None


def _near(text: str, pos: int, words, window: int = 35) -> bool:
    """Есть ли рядом слово из списка (например, «наберу» рядом с «в понедельник»)."""
    chunk = text[max(0, pos - window):pos + window]
    return any(w in chunk for w in words)


def find_date(text: str, call_day: date) -> dict | None:
    """Дата игры: явная («31 октября»), относительная («завтра», «в субботу») или «17-го числа».

    Даты-обещания перезвонить («в понедельник наберу») отбрасываются: это не день игры.
    """
    t = norm_text(text)

    for stem, month in MONTHS:
        m = re.search(stem, t)
        if not m:
            continue
        before = t[max(0, m.start() - 22):m.start()]
        day = None
        digits = re.findall(r"\b(\d{1,2})\b", before)
        if digits:
            day = int(digits[-1])
        if day is None:
            day = _word_number(before)
        if not day or not 1 <= day <= 31:
            continue
        year = call_day.year
        try:
            d = date(year, month, day)
        except ValueError:
            continue
        if d < call_day:  # «31 октября» сказали в ноябре — значит следующий год
            d = date(year + 1, month, day)
        return {"date": d.isoformat(), "kind": "explicit", "text": f"{day} {MONTH_GEN[month - 1]}"}

    # «завтра», «послезавтра» — но не «завтра вам перезвоню»
    for word, delta in (("послезавтра", 2), ("завтра", 1)):
        for m in re.finditer(rf"\b{word}\b", t):
            if _near(t, m.start(), CALLBACK):
                continue
            d = call_day + timedelta(days=delta)
            return {"date": d.isoformat(), "kind": "relative", "text": word}

    # «в субботу», «в пятницу» — тоже мимо обещаний позвонить
    for pattern, num in WEEKDAYS:
        m = re.search(pattern, t)
        if m and not _near(t, m.start(), CALLBACK):
            ahead = (num - call_day.weekday()) % 7 or 7
            d = call_day + timedelta(days=ahead)
            return {"date": d.isoformat(), "kind": "relative", "text": m.group(0)}

    # «17-го числа» — день без месяца: этот месяц, а если уже прошёл — следующий
    m = re.search(r"\b(\d{1,2})\s+(?:го|числа)\b", t)
    if m and not _near(t, m.start(), ("лет", "рубл", "тысяч", "шарик", "минут")):
        day = int(m.group(1))
        if 1 <= day <= 31:
            year, month = call_day.year, call_day.month
            if day < call_day.day:
                month += 1
                if month > 12:
                    year, month = year + 1, 1
            d = date(year, month, day)
            return {"date": d.isoformat(), "kind": "explicit", "text": m.group(0)}
    return None


# Числа из служебных фраз — не про игроков: «до 35 человек» (вместимость беседки),
# «если больше 16 человек» (акция), «если вы ставите на 2 участника» (пример расчёта).
SERVICE_BEFORE = (r"(?<![а-я])до\s", r"больше", r"свыше", r"если вы", r"не более", r"минимум", r"тариф")
SERVICE_AFTER = ("в подарок", "подарок", "вместимост", "скидк", "максимум")
# Вопрос про цену сам по себе не мешает: «сколько стоит на 10 человек» — это заявка.
# Но число без слова «человек/участник» рядом он отсекает: «сколько будет стоить 5 бое» — не люди.
PRICE_BEFORE = ("стоит", "стоимость", "цену", "цена", "прайс")
# Так говорит заказчик: «нас будет», «у нас», «планируем», «примерно».
# «приедут» здесь намеренно нет: «приедут либо 10 либо 14 утра» — это время, а не группа.
CLIENT_MARKERS = ("нас", "у нас", "будет", "планиру", "ожида", "состав",
                  "всего", "где то", "примерно", "около", "порядка", "типа")


def find_players(text: str) -> dict | None:
    """Число игроков — самое правдоподобное, а не первое попавшееся.

    Расшифровка приходит одной строкой: слова клиента и администратора не разделены, поэтому
    служебные числа («на 2 участника» — пример расчёта, «если больше 16 человек» — акция,
    «до 35 человек» — вместимость беседки) отбрасываем, а берём то, что сказано рядом со словами
    заказчика («нас будет», «планируем», «примерно»). Если подходящих чисел нет — ищем число словом.
    """
    t = norm_text(text)
    unit = "|".join(PEOPLE_UNITS)
    bad = "|".join(BAD_UNITS)

    best = None  # (очки, позиция, число, фраза)
    for m in re.finditer(r"\b(\d{1,3})\b", t):
        n = int(m.group(1))
        if not 2 <= n <= 500:
            continue
        before, after = t[max(0, m.start() - 48):m.start()], t[m.end():m.end() + 24]
        if re.search(r"\d\s*$", before):
            continue                                  # «1 5 игры», «30 30» — продолжение другого числа
        if re.match(rf"\s*(?:{bad})", after):
            continue                                  # «3000 рублей», «500 шариков», «6 часов»
        if any(re.search(p, before) for p in SERVICE_BEFORE) or any(w in after[:16] for w in SERVICE_AFTER):
            continue                                  # «до 35 человек», «больше 16 человек в подарок»
        if re.match(r"\s*(?:\d{1,3}\s*)?(?:лет|года|год)\b", after):
            continue                                  # «11 12 лет», «12 лет» — возраст, а не игроки
        unit_near = bool(re.match(rf"\s*(?:{unit})", after))
        if not unit_near:
            for um in re.finditer(rf"(?:{unit})", before):
                tail = before[um.end():]
                if re.search(r"\d", before[max(0, um.start() - 6):um.start()]):
                    continue        # «30 человек 15» — слово «человек» относится к 30, а не к 15
                if re.fullmatch(r"\s*(?:где то\s+)?(?:примерно\s+)?", tail):
                    unit_near = True
                    break
        if not unit_near and any(w in before for w in PRICE_BEFORE):
            continue                                  # «сколько будет стоить 5 бое» — цена, не группа
        marked = any(w in before for w in CLIENT_MARKERS)
        if not (unit_near or marked):
            continue                                  # число без «человек/участник» и без слов заказчика
        score = (3 if unit_near else 0) + (2 if marked else 0)
        if best is None or score > best[0]:
            best = (score, m.start(), n, (m.group(0) + " " + after.strip().split(" ")[0]).strip())

    if best:
        return {"players": best[2], "text": best[3]}

    # Число словом: «придут два человека», «нас будет тридцать человек», «человек тридцать».
    card = "|".join(w for w, _ in CARDINALS)
    m = re.search(rf"\b({card})\s+(?:{unit})", t)
    if m:
        for word, val in CARDINALS:
            if m.group(1) == word and 2 <= val <= 500:
                return {"players": val, "text": m.group(0).strip()}
    m = re.search(rf"(?:{unit})\s+(?:где то\s+)?((?:двадцат|тридцат|сорок|пятьдесят)\w*)", t)
    if m:
        n = _word_number(m.group(1))
        if n and 2 <= n <= 500:
            return {"players": n, "text": m.group(0).strip()}
    return None


# «Корпоративные заказы — от 30 человек» (Артём, 11.10.2026): большая группа без детских,
# школьных и «дней рождения» признаков — это корпоратив.
CORP_MIN_PLAYERS = 30


def classify(text: str, call_day: date) -> dict:
    """Полная разметка одного разговора.

    Дату и число игроков берём только у звонков «по нашей тематике»: если по тексту
    не видно ни игры, ни группы (`нецелевой`, `недозвон`), любое число — случайное.
    Но если названа большая группа (от 30 человек), звонок и «непонятно» становится корпоративом.
    """
    res = detect_type(text)
    game = res["type"] not in ("непонятно", "нецелевой", "недозвон")
    players = find_players(text) if res["type"] not in ("нецелевой", "недозвон") else None
    if players and players["players"] >= CORP_MIN_PLAYERS and res["type"] in ("просто_игра", "непонятно"):
        res = {"type": "корпоратив", "why": f"{players['players']} человек"}
        game = True
    res["date"] = find_date(text, call_day) if game else None
    res["players"] = players if game else None
    res["source"] = "rules-v3"
    return res
